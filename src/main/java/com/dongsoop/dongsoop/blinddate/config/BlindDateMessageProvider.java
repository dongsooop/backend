    public List<String> getRandomEventMessages(int count) {
        List<String> messages = new ArrayList<>(Arrays.asList(EVENT_MESSAGES));
        Collections.shuffle(messages);
        return messages.subList(0, Math.min(count, messages.size()));
    }

